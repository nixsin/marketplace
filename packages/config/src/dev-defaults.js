/**
 * The ports and URLs every NON-DEPLOYED environment uses.
 *
 * THESE ARE NOT FALLBACKS, and the distinction is the whole point. Nothing
 * reads them automatically: `resolvePublicUrl` still refuses to invent a
 * value, and a variable left unset is still reported by the environment
 * contract. They exist so the config FILES that must state a value -- and
 * there are six of them -- state the same one, instead of six separate
 * `http://localhost:3000` literals drifting apart in silence.
 *
 * The URLs are DERIVED from the ports rather than written out again, so
 * "the API listens on 4000" is one fact in one place. Changing the port
 * cannot leave a URL behind pointing at the old one.
 *
 * TODAY THE ONLY CONSUMER IS the environment contract, which reads them as
 * each rule's `devValue`. The config files that state these values by hand
 * -- both .env.example files, docker-compose.yml and ci.yml -- are not yet
 * generated from or pinned to them; that is a later change in this series,
 * and until it lands those literals and these constants can still drift.
 */
/**
 * The local Postgres and Redis a developer machine, the dev stack and CI all
 * talk to.
 *
 * Here for the same reason the ports are: these values appeared as literals in
 * docker-compose.yml (twice — the service's own config and the URL the API
 * connects with), in ci.yml (twice more, in two different jobs), and in the
 * contract's own devValue. Five copies of "the dev database password is
 * postgres", any of which could be changed alone.
 *
 * NOT a credential in the secret sense: this is the throwaway account a local
 * container creates for itself. The real one is generated by Render and read
 * by Terraform, and never appears in this repository.
 */
export const POSTGRES_PORT = 5432;
export const REDIS_PORT = 6379;
export const DEV_POSTGRES_USER = "postgres";
export const DEV_POSTGRES_PASSWORD = "postgres";
export const DEV_POSTGRES_DB = "medinstru";

/** What a process on the HOST uses — a laptop, or a CI runner with a service container. */
export const DEV_DATABASE_URL = `postgresql://${DEV_POSTGRES_USER}:${DEV_POSTGRES_PASSWORD}@localhost:${POSTGRES_PORT}/${DEV_POSTGRES_DB}?schema=public`;

/**
 * What a process INSIDE the Docker network uses.
 *
 * The only difference is the hostname: compose resolves service names, and a
 * container cannot reach the host's `localhost`. This pair being derived from
 * one set of parts is what stops the two from drifting -- which they can,
 * silently, because each works perfectly in its own context.
 */
export const DOCKER_DATABASE_URL = `postgresql://${DEV_POSTGRES_USER}:${DEV_POSTGRES_PASSWORD}@postgres:${POSTGRES_PORT}/${DEV_POSTGRES_DB}?schema=public`;
export const DOCKER_REDIS_URL = `redis://redis:${REDIS_PORT}`;

export const API_DEFAULT_PORT = 4000;
export const WEB_DEFAULT_PORT = 3000;

export const DEV_API_URL = `http://localhost:${API_DEFAULT_PORT}/graphql`;
export const DEV_SITE_URL = `http://localhost:${WEB_DEFAULT_PORT}`;

